import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import * as ts from "typescript/unstable/ast"
import { API } from "typescript/unstable/sync"

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const configPath = path.join(projectRoot, "tsconfig.json")
const api = new API()
const snapshot = api.updateSnapshot({ openProjects: [configPath] })
const project = snapshot.getProjects().find((candidate) => candidate.configFileName === configPath)
if (!project) fail(`TypeScript did not load ${configPath}`)
const { checker, program } = project
const capabilityNames = [
	"steps",
	"data-flow",
	"map",
	"loop",
	"foreach",
	"parallel",
	"branch",
	"workflow",
	"advanced-agent",
]
const capabilities = new Set(capabilityNames)
const entries = Object.fromEntries(capabilityNames.map((name) => [name, []]))

for (const fileName of program.getSourceFileNames()) {
	const sourceFile = program.getSourceFile(fileName)
	if (!sourceFile) continue
	if (!isFlowSource(sourceFile.fileName)) continue
	visit(sourceFile)
}

for (const capability of capabilityNames) {
	if (entries[capability].length === 0) fail(`No TSDoc entries found for authoring capability "${capability}"`)
}

const capabilityType = capabilityNames.map((name) => JSON.stringify(name)).join(" | ")
const generated = [
	"// Generated by `pnpm docs:authoring` from public declarations and TSDoc in src/flow.",
	"// Do not edit this file directly.",
	"// biome-ignore-all lint/suspicious/noTemplateCurlyInString: documentation strings contain TypeScript examples.",
	"",
	`export type AuthoringCapability = ${capabilityType}`,
	"",
	"export interface GeneratedAuthoringEntry {",
	"\treadonly symbol: string",
	"\treadonly signature: string",
	"\treadonly documentation: string",
	"}",
	"",
	"export const GENERATED_AUTHORING_REFERENCE: Readonly<",
	"\tRecord<AuthoringCapability, readonly GeneratedAuthoringEntry[]>",
	`> = ${JSON.stringify(entries, null, "\t")}`,
	"",
].join("\n")

const outputPath = path.join(projectRoot, "src/host/builtin/generated/authoring-reference.ts")
await mkdir(path.dirname(outputPath), { recursive: true })
await writeFile(outputPath, generated, "utf8")
snapshot.dispose()
api.close()
process.stdout.write(`Generated ${path.relative(projectRoot, outputPath)}\n`)

function visit(node) {
	const symbol = declarationSymbol(node)
	if (symbol) {
		const tags = symbol.getJsDocTags(checker)
		const selected = tags
			.filter((tag) => tag.name === "workflowCapability")
			.flatMap((tag) => tagText(tag).split(/[\s,]+/))
			.filter(Boolean)
		for (const capability of selected) {
			if (!capabilities.has(capability)) {
				fail(`${sourceLocation(node)} uses unknown @workflowCapability "${capability}"`)
			}
			entries[capability].push({
				symbol: displayName(node),
				signature: displaySignature(node),
				documentation: displayDocumentation(symbol, tags),
			})
		}
	}
	node.forEachChild(visit)
}

function declarationSymbol(node) {
	if (!node.name || !ts.isIdentifier(node.name)) return undefined
	if (
		!ts.isFunctionDeclaration(node) &&
		!ts.isInterfaceDeclaration(node) &&
		!ts.isTypeAliasDeclaration(node) &&
		!ts.isMethodSignatureDeclaration(node)
	) {
		return undefined
	}
	return checker.getSymbolAtLocation(node.name)
}

function displayName(node) {
	const ownName = node.name.text
	if (ts.isMethodSignatureDeclaration(node) && ts.isInterfaceDeclaration(node.parent)) {
		return `${node.parent.name.text}.${ownName}`
	}
	return ownName
}

function displaySignature(node) {
	if (ts.isFunctionDeclaration(node) || ts.isMethodSignatureDeclaration(node)) {
		const typeParameters = node.typeParameters
			? `<${node.typeParameters.map((parameter) => normalize(parameter.getText())).join(", ")}>`
			: ""
		const parameters = node.parameters.map((parameter) => normalize(parameter.getText())).join(", ")
		const returnType = node.type ? `: ${normalize(node.type.getText())}` : ""
		return `${displayName(node)}${typeParameters}(${parameters})${returnType}`
	}
	if (ts.isTypeAliasDeclaration(node)) {
		const typeParameters = node.typeParameters
			? `<${node.typeParameters.map((parameter) => normalize(parameter.getText())).join(", ")}>`
			: ""
		return `type ${node.name.text}${typeParameters} = ${normalize(node.type.getText())}`
	}
	if (ts.isInterfaceDeclaration(node)) {
		const typeParameters = node.typeParameters
			? `<${node.typeParameters.map((parameter) => normalize(parameter.getText())).join(", ")}>`
			: ""
		const members = node.members.map((member) => normalize(member.getText())).join(" ")
		return `interface ${node.name.text}${typeParameters} { ${members} }`
	}
	fail(`${sourceLocation(node)} is not a supported documented declaration`)
}

function displayDocumentation(symbol, tags) {
	const sections = []
	const summary = symbol.getDocumentationComment(checker).trim()
	if (summary) sections.push(summary)
	for (const tag of tags) {
		if (tag.name === "workflowCapability") continue
		const content = tagText(tag).trim()
		if (!content) continue
		const label =
			tag.name === "defaultValue"
				? "Default"
				: tag.name === "remarks"
					? "Remarks"
					: tag.name[0].toUpperCase() + tag.name.slice(1)
		sections.push(`${label}: ${content}`)
	}
	if (sections.length === 0) fail(`${symbol.getName()} has @workflowCapability but no documentation`)
	return sections.join("\n\n")
}

function tagText(tag) {
	return tag.text ?? ""
}

function normalize(value) {
	return value.replace(/\s+/g, " ").trim()
}

function isFlowSource(fileName) {
	const relative = path.relative(path.join(projectRoot, "src/flow"), fileName)
	return relative !== "" && !relative.startsWith("..") && !path.isAbsolute(relative)
}

function sourceLocation(node) {
	const sourceFile = node.getSourceFile()
	const line = sourceFile.text.slice(0, node.getStart(sourceFile)).split("\n").length
	return `${path.relative(projectRoot, sourceFile.fileName)}:${line}`
}

function fail(message) {
	throw new Error(message)
}
