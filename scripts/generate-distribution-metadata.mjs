import { execFileSync } from "node:child_process"
import { readFile, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import path from "node:path"
import { fileURLToPath } from "node:url"

// Stamps the package-owned distribution metadata: the framework version, package-manager pin, and
// toolchain versions that `prepareWorkflowPackage` writes into a project's `.kimchi/workflows/package.json`.
// The metadata must be ordinary executable code so a bundled executable (a Bun binary) carries it without
// a workflows `package.json` present beside the executable. package.json remains the source of truth; the
// release flow re-runs this generator in `prepack`, after its version stamp, so publication ships the
// release version in both the packed source and the packed build.

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const manifestPath = path.resolve(argumentValue("--manifest") ?? path.join(projectRoot, "package.json"))
const outputPath = path.resolve(argumentValue("--output") ?? path.join(projectRoot, "src/host/distribution.ts"))

const manifest = JSON.parse(await readFile(manifestPath, "utf8"))

const distribution = {
	name: required(manifest.name, "package name"),
	version: required(manifest.version, "package version"),
	packageManager: required(
		manifest.kimchiWorkflows?.packageManager ?? manifest.packageManager,
		"framework package manager",
	),
	toolchain: {
		piCodingAgent: required(
			manifest.devDependencies?.["@earendil-works/pi-coding-agent"],
			"devDependency @earendil-works/pi-coding-agent",
		),
		piTui: required(manifest.devDependencies?.["@earendil-works/pi-tui"], "devDependency @earendil-works/pi-tui"),
		typebox: required(manifest.devDependencies?.typebox, "devDependency typebox"),
		typesNode: required(manifest.dependencies?.["@types/node"], "dependency @types/node"),
		typescript: required(manifest.dependencies?.typescript, "dependency typescript"),
		vitest: required(manifest.dependencies?.vitest, "dependency vitest"),
	},
}

const unformattedGenerated = [
	"// Generated by `pnpm dist:metadata` from package.json.",
	"// Do not edit this file directly.",
	"",
	"/**",
	" * Package-owned distribution metadata, stamped into the source so a bundled executable carries",
	" * the release identity as ordinary code. Production workflow project preparation derives the",
	" * `.kimchi/workflows/package.json` contract exclusively from this object.",
	" */",
	"export interface DistributionMetadata {",
	"\treadonly name: string",
	"\treadonly version: string",
	"\treadonly packageManager: string",
	"\treadonly toolchain: {",
	"\t\treadonly piCodingAgent: string",
	"\t\treadonly piTui: string",
	"\t\treadonly typebox: string",
	"\t\treadonly typesNode: string",
	"\t\treadonly typescript: string",
	"\t\treadonly vitest: string",
	"\t}",
	"}",
	"",
	`export const distribution: DistributionMetadata = ${JSON.stringify(distribution, null, "\t")}`,
	"",
].join("\n")
const require = createRequire(import.meta.url)
const generated = execFileSync(
	process.execPath,
	[require.resolve("@biomejs/biome/bin/biome"), "format", "--stdin-file-path", outputPath],
	{ input: unformattedGenerated, encoding: "utf8" },
)

if (process.argv.includes("--check")) {
	let actual
	try {
		actual = await readFile(outputPath, "utf8")
	} catch {
		fail(`${path.relative(projectRoot, outputPath)} is missing; run pnpm dist:metadata`)
	}
	if (actual !== generated) fail(`${path.relative(projectRoot, outputPath)} is stale; run pnpm dist:metadata`)
} else {
	await writeFile(outputPath, generated, "utf8")
}
process.stdout.write(
	`${process.argv.includes("--check") ? "Checked" : "Generated"} ${path.relative(projectRoot, outputPath)}\n`,
)

function required(value, label) {
	if (typeof value === "string" && value.trim()) return value
	fail(`${label} is missing from package.json`)
}

function argumentValue(name) {
	const inline = process.argv.find((argument) => argument.startsWith(`${name}=`))
	if (inline) {
		const value = inline.slice(name.length + 1)
		if (value) return value
		fail(`${name} requires a path`)
	}
	const index = process.argv.indexOf(name)
	if (index < 0) return undefined
	const value = process.argv[index + 1]
	if (!value || value.startsWith("--")) fail(`${name} requires a path`)
	return value
}

function fail(message) {
	throw new Error(message)
}
